-- Ideenwerkstatt – Datenbank für Supabase
-- Im Supabase-Dashboard unter "SQL Editor" einfügen und ausführen.
-- Das Skript kann gefahrlos mehrmals ausgeführt werden.

-- ---------------------------------------------------------------
-- Tabellen
-- ---------------------------------------------------------------

create table if not exists public.ideas (
  id          bigint generated by default as identity primary key,
  title       text        not null default '',
  category    text        not null default 'Allgemein',
  status      text        not null default 'Neu'
              check (status in ('Neu', 'In Diskussion', 'Favorit', 'Verworfen')),
  priority    text        not null default 'Mittel'
              check (priority in ('Niedrig', 'Mittel', 'Hoch')),
  description text        not null default '',
  owner       text        not null default '',
  tags        text[]      not null default '{}',
  votes       integer     not null default 0 check (votes >= 0),
  pros        text[]      not null default '{}',
  cons        text[]      not null default '{}',
  created_at  timestamptz not null default now()
);

create table if not exists public.comments (
  id         bigint generated by default as identity primary key,
  idea_id    bigint      not null references public.ideas (id) on delete cascade,
  author     text        not null default 'Anonym',
  text       text        not null,
  created_at timestamptz not null default now()
);

create index if not exists comments_idea_id_idx on public.comments (idea_id);

-- ---------------------------------------------------------------
-- Abstimmen: Stimmen direkt in der Datenbank hoch-/runterzählen,
-- damit sich gleichzeitige Klicks nicht gegenseitig überschreiben
-- ---------------------------------------------------------------

create or replace function public.vote_idea(idea_id bigint, delta integer)
returns integer
language sql
as $$
  update public.ideas
  set votes = greatest(0, votes + sign(delta)::integer)
  where id = idea_id
  returning votes;
$$;

-- ---------------------------------------------------------------
-- Zugriff: Schulprojekt ohne Login – jeder mit dem anon-Key
-- darf lesen und schreiben
-- ---------------------------------------------------------------

alter table public.ideas enable row level security;
alter table public.comments enable row level security;

drop policy if exists "ideas_public_access" on public.ideas;
create policy "ideas_public_access" on public.ideas
  for all to anon, authenticated using (true) with check (true);

drop policy if exists "comments_public_access" on public.comments;
create policy "comments_public_access" on public.comments
  for all to anon, authenticated using (true) with check (true);

-- ---------------------------------------------------------------
-- Realtime: Änderungen live an alle offenen Browser schicken
-- ---------------------------------------------------------------

do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime' and tablename = 'ideas'
  ) then
    alter publication supabase_realtime add table public.ideas;
  end if;

  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime' and tablename = 'comments'
  ) then
    alter publication supabase_realtime add table public.comments;
  end if;
end $$;

